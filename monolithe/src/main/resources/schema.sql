-- Base de données de BankApp.
-- Chaque application possède son schéma, mais tous les schémas vivent dans la même base :
-- rien n'empêche une application de lire ou d'écrire dans le schéma d'une autre.

-- Application Comptes
CREATE SCHEMA CPT_DB;
CREATE TABLE CPT_DB.T_COMPTE (
    ID_COMPTE  VARCHAR(10) PRIMARY KEY,
    ID_CLIENT  VARCHAR(10) NOT NULL,
    SOLDE      DECIMAL(12, 2) NOT NULL
);
CREATE TABLE CPT_DB.T_MOUVEMENT (
    ID          INT AUTO_INCREMENT PRIMARY KEY,
    ID_COMPTE   VARCHAR(10) NOT NULL,
    DATE_MVT    DATE NOT NULL,
    MONTANT     DECIMAL(12, 2) NOT NULL,
    LIBELLE     VARCHAR(60)
);

-- Application Prêts
CREATE SCHEMA PRET_DB;
CREATE TABLE PRET_DB.T_PRET (
    ID_PRET     INT GENERATED BY DEFAULT AS IDENTITY (START WITH 100) PRIMARY KEY,
    ID_CLIENT   VARCHAR(10) NOT NULL,
    MONTANT     DECIMAL(12, 2) NOT NULL,
    DUREE_MOIS  INT NOT NULL,
    STATUT      VARCHAR(10) NOT NULL
);
CREATE TABLE PRET_DB.T_ECHEANCE (
    ID_PRET         INT NOT NULL,
    NUMERO          INT NOT NULL,
    DATE_ECHEANCE   DATE NOT NULL,
    MONTANT         DECIMAL(12, 2) NOT NULL
);

-- Application Risque
CREATE SCHEMA RISK_DB;
CREATE TABLE RISK_DB.T_SCORE (
    ID           VARCHAR(10) PRIMARY KEY,
    SCORE        INT NOT NULL,
    DATE_CALCUL  DATE NOT NULL
);
CREATE TABLE RISK_DB.T_INCIDENT (
    ID              INT AUTO_INCREMENT PRIMARY KEY,
    ID_CLIENT       VARCHAR(10) NOT NULL,
    DATE_INCIDENT   DATE NOT NULL,
    TYPE_INCIDENT   VARCHAR(30) NOT NULL
);

-- Application CRM
CREATE SCHEMA CRM_DB;
CREATE TABLE CRM_DB.T_CLIENT (
    ID_CLIENT       VARCHAR(10) PRIMARY KEY,
    NOM             VARCHAR(50) NOT NULL,
    DATE_NAISSANCE  DATE NOT NULL,
    TELEPHONE       VARCHAR(15) NOT NULL,
    EMAIL           VARCHAR(50) NOT NULL
);
